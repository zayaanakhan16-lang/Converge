import type { NativeStackScreenProps } from '@react-navigation/native-stack';
import { CheckCircle2, Lightbulb, RotateCcw, Sparkles, TrendingUp } from 'lucide-react-native';
import { useState } from 'react';
import { Pressable, StyleSheet, View } from 'react-native';

import { DemoDataBanner, FeatureUnavailable } from '../../components/ui/Banners';
import { Button } from '../../components/ui/Button';
import { Card, Screen, SectionHeader } from '../../components/ui/Layout';
import { Text } from '../../components/ui/Text';
import { TextField } from '../../components/ui/TextField';
import { aiUnavailableReason } from '../../constants/config';
import { useTheme } from '../../context/ThemeContext';
import { useCoachSession } from '../../features/coach/useCoachSession';
import { COACH_SCENARIOS, MODEL_COACH_LABEL, RULE_BASED_COACH_LABEL } from '../../features/coach/scenarios';
import type { DiscoverStackParamList } from '../../navigation/types';
import { radius, spacing } from '../../theme';

type Props = NativeStackScreenProps<DiscoverStackParamList, 'Coach'>;

/**
 * Conversation coach.
 *
 * A practice space with six defined scenarios, not an open chat. Feedback is
 * structured into strengths, improvements, one concrete revision and one next
 * step, and the screen always states whether a model or the rule engine
 * produced it.
 */
export function CoachScreen({ navigation }: Props) {
  const { theme } = useTheme();
  const [scenarioId, setScenarioId] = useState(COACH_SCENARIOS[0].id);
  const [draft, setDraft] = useState('');
  const session = useCoachSession();

  const scenario = COACH_SCENARIOS.find((item) => item.id === scenarioId) ?? COACH_SCENARIOS[0];
  const latest = [...session.messages].reverse().find((message) => message.feedback);
  const feedback = latest?.feedback;

  const submit = async () => {
    if (draft.trim().length < 4) return;
    await session.submit(scenarioId, draft);
  };

  return (
    <Screen scroll edges={['top']}>
      <View style={styles.stack}>
        <View style={styles.heading}>
          <Text token="title1">Conversation coach</Text>
          <Text token="body" tone="secondary">
            Practise a specific situation and get concrete feedback before you send anything to
            a real member.
          </Text>
        </View>

        {aiUnavailableReason ? (
          <FeatureUnavailable
            title="Model-backed coaching is not configured"
            reason={`${aiUnavailableReason} Converge's own rule-based analyser is used instead, and the feedback below is labelled accordingly.`}
            remedy="Set EXPO_PUBLIC_BACKEND_URL in mobile/.env"
          />
        ) : (
          <DemoDataBanner
            label="Model coaching enabled"
            message="Feedback is generated by the Converge backend. Practice messages are not stored on your profile and are never sent to other members."
          />
        )}

        <SectionHeader
          title="What do you want to practise?"
          subtitle="Choose one situation. You can switch at any time."
        />
        <View style={styles.scenarioList}>
          {COACH_SCENARIOS.map((item) => {
            const selected = item.id === scenarioId;
            return (
              <Pressable
                key={item.id}
                onPress={() => {
                  setScenarioId(item.id);
                  session.reset();
                  setDraft('');
                }}
                accessibilityRole="radio"
                accessibilityState={{ selected }}
                accessibilityLabel={`${item.title}. ${item.description}`}
                style={[
                  styles.scenario,
                  {
                    backgroundColor: selected ? theme.colors.primary : theme.colors.surface,
                    borderColor: selected ? theme.colors.primary : theme.colors.border,
                  },
                ]}
              >
                <Text
                  token="bodyStrong"
                  color={selected ? theme.colors.onPrimary : theme.colors.textPrimary}
                >
                  {item.title}
                </Text>
                <Text
                  token="caption"
                  color={selected ? theme.colors.onPrimary : theme.colors.textSecondary}
                >
                  {item.description}
                </Text>
              </Pressable>
            );
          })}
        </View>

        <Card>
          <SectionHeader title={scenario.title} subtitle={scenario.openingPrompt} />
          <TextField
            label="Your message"
            value={draft}
            onChangeText={setDraft}
            hint={`${draft.length}/600 characters. Write it as you would actually send it.`}
            placeholder="Write your message here"
            multiline
            numberOfLines={5}
            maxLength={600}
          />
          <View style={styles.composeActions}>
            <Button
              label="Get feedback"
              onPress={submit}
              loading={session.busy}
              disabled={draft.trim().length < 4}
              icon={<Sparkles size={16} color={theme.colors.onPrimary} strokeWidth={2} />}
              fullWidth
            />
            <Button
              label="Clear"
              variant="ghost"
              onPress={() => {
                setDraft('');
                session.reset();
              }}
              icon={<RotateCcw size={15} color={theme.colors.accent} strokeWidth={2} />}
              fullWidth
            />
          </View>
        </Card>

        {session.fallbackNotice ? (
          <DemoDataBanner label="Fallback used" message={session.fallbackNotice} />
        ) : null}

        {session.error ? (
          <Card>
            <Text token="body" tone="danger">
              {session.error}
            </Text>
          </Card>
        ) : null}

        {feedback ? (
          <>
            <Card>
              <View style={styles.feedbackHeader}>
                <Text token="title3">Feedback</Text>
                <View
                  style={[
                    styles.providerTag,
                    { backgroundColor: theme.colors.surfaceSunken, borderColor: theme.colors.border },
                  ]}
                >
                  <Text token="label" tone="muted">
                    {feedback.generatedByModel ? MODEL_COACH_LABEL : RULE_BASED_COACH_LABEL}
                  </Text>
                </View>
              </View>
              <Text token="caption" tone="muted">
                {feedback.generatedByModel
                  ? 'Produced by the configured model through the Converge backend.'
                  : `Produced by the deterministic rule engine (${feedback.provider}). No model call was made.`}
              </Text>
            </Card>

            <Card>
              <SectionHeader title="What works" />
              {feedback.strengths.map((item) => (
                <View key={item} style={styles.bullet}>
                  <CheckCircle2 size={15} color={theme.colors.success} strokeWidth={2.2} />
                  <Text token="body" tone="secondary" style={styles.bulletText}>
                    {item}
                  </Text>
                </View>
              ))}
            </Card>

            {feedback.improvements.length > 0 ? (
              <Card>
                <SectionHeader
                  title="What to change"
                  subtitle="Each point names the exact phrase or gap it refers to."
                />
                {feedback.improvements.map((item) => (
                  <View key={item} style={styles.bullet}>
                    <TrendingUp size={15} color={theme.colors.warning} strokeWidth={2.2} />
                    <Text token="body" tone="secondary" style={styles.bulletText}>
                      {item}
                    </Text>
                  </View>
                ))}
              </Card>
            ) : null}

            <Card>
              <SectionHeader
                title="A revision you could send"
                subtitle="Built from your own sentences, so it still sounds like you."
              />
              <View
                style={[
                  styles.revision,
                  { backgroundColor: theme.colors.surfaceSunken, borderColor: theme.colors.border },
                ]}
              >
                <Text token="body">{feedback.suggestedRevision}</Text>
              </View>
              <Button
                label="Use this revision"
                variant="secondary"
                onPress={() => setDraft(feedback.suggestedRevision)}
                fullWidth
              />
            </Card>

            <Card>
              <SectionHeader title="Next step" />
              <View style={styles.bullet}>
                <Lightbulb size={15} color={theme.colors.accent} strokeWidth={2.2} />
                <Text token="body" tone="secondary" style={styles.bulletText}>
                  {feedback.nextStep}
                </Text>
              </View>
              <Button
                label="Back to recommendations"
                variant="ghost"
                onPress={() => navigation.goBack()}
                fullWidth
              />
            </Card>
          </>
        ) : null}

        {session.messages.length === 0 && !session.busy ? (
          <Text token="caption" tone="muted">
            Nothing is sent from this screen. Practice messages stay on your device and are only
            shared with the coach service when model coaching is configured.
          </Text>
        ) : null}
      </View>
    </Screen>
  );
}

const styles = StyleSheet.create({
  stack: { gap: spacing.lg, paddingTop: spacing.md, paddingBottom: spacing.xxxl },
  heading: { gap: spacing.sm },
  scenarioList: { gap: spacing.sm },
  scenario: {
    borderRadius: radius.lg,
    borderWidth: StyleSheet.hairlineWidth * 2,
    padding: spacing.lg,
    gap: spacing.xxs,
  },
  composeActions: { gap: spacing.sm, marginTop: spacing.md },
  feedbackHeader: {
    flexDirection: 'row',
    alignItems: 'center',
    justifyContent: 'space-between',
    gap: spacing.md,
    marginBottom: spacing.sm,
  },
  providerTag: {
    paddingHorizontal: spacing.sm,
    paddingVertical: spacing.xxs,
    borderRadius: radius.sm,
    borderWidth: StyleSheet.hairlineWidth * 2,
  },
  bullet: { flexDirection: 'row', gap: spacing.md, alignItems: 'flex-start', marginBottom: spacing.md },
  bulletText: { flex: 1 },
  revision: {
    padding: spacing.lg,
    borderRadius: radius.md,
    borderWidth: StyleSheet.hairlineWidth * 2,
    marginBottom: spacing.md,
  },
});
